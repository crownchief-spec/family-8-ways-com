import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { loadSiteConfig, renderPage } from './render.mjs';
import { renderPhotographerProfile } from './photographer-profile.mjs';
const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const cfg = loadSiteConfig();
const p = JSON.parse(readFileSync(join(ROOT, 'data/photographer-profile.json'), 'utf8'));
const path = join(ROOT, 'about/index.html');
mkdirSync(dirname(path), {recursive:true});
let html = renderPage(cfg, { title:'關於小巴老師｜近20年專業攝影、親子寫真與海外旅拍', description:'八威創意有限公司小巴老師，近20年專業攝影經驗與約60趟海外工作，服務包含親子寫真、商業攝影、活動、美食與婚禮紀錄；滑雪攝影近10年，能手持專業單眼相機邊滑邊拍。', canonical:cfg.site.url+'/about/', body:'<div class="container">'+renderPhotographerProfile(p,{family:true})+'</div>', ogImage:p.images.camera.src });
html = html.replace('</head>','<link rel="stylesheet" href="/assets/css/photographer-profile.css?v=20261122"></head>');
writeFileSync(path,html);
const homePath = join(ROOT,'index.html');
let home = readFileSync(homePath,'utf8').replace(/<!-- photographer-profile:start -->[\s\S]*?<!-- photographer-profile:end -->/g,'');
home = home.replaceAll('50 趟以上海外旅拍','約60趟海外拍攝');
const photo = p.images.skiPortrait;
const feature = `<!-- photographer-profile:start --><section class="container ski-home family-ski"><div><p class="ski-eyebrow">八威創意有限公司 · 小巴老師</p><h2>近20年的攝影經驗，<br>留下每個家庭自己的故事。</h2><p>累積約60趟海外拍攝工作，從商業品牌、活動紀錄與美食影像，到親子寫真、家庭旅拍與婚禮紀錄。滑雪攝影經驗近10年，能手持專業單眼相機邊滑邊拍。</p><a class="btn btn--secondary" href="/about/">認識小巴老師與拍攝經歷</a></div><img src="${photo.src}" alt="${photo.alt}" title="${photo.title}" width="${photo.width}" height="${photo.height}" loading="lazy" decoding="async" style="width:auto;max-width:100%;height:260px;object-fit:contain;justify-self:center"></section><!-- photographer-profile:end -->`;
const marker='<!-- ski-spotlight:end -->';
if(home.includes(marker))home=home.replace(marker,marker+feature);else home=home.replace('</main>',feature+'</main>');
writeFileSync(homePath,home);
console.log('Built photographer profile and Family homepage introduction');
